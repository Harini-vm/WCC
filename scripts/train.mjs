// Train Baton's two models from data/ml-train.js and write js/engine/ml-model.js.
// Deterministic: same data -> same weights. Run: node scripts/train.mjs
import fs from "node:fs";
import { TRAIN } from "../data/ml-train.js";
import { TEST } from "../data/ml-test.js";
import { ML_LABELS, featuresOf, charGrams } from "../js/engine/ml.js";

const K = ML_LABELS.length;
const overlap = TRAIN.filter(([s]) => TEST.some(([t]) => t.toLowerCase() === s.toLowerCase()));
if (overlap.length) throw new Error("Train/test overlap: " + overlap.map((x) => x[0]).join(" | "));

// ---------- Extractor: softmax regression, L2, deterministic SGD ----------
const X = TRAIN.map(([s]) => featuresOf(s));
const Y = TRAIN.map(([, l]) => ML_LABELS.indexOf(l));
const W = {};
const get = (f) => (W[f] ||= new Array(K).fill(0));
const EPOCHS = 300, L2 = 0.0008;
let lr = 0.2;
let seed = 7;
const rand = () => ((seed = (seed * 1103515245 + 12345) % 2147483648) / 2147483648);
const idx = TRAIN.map((_, i) => i);
for (let ep = 0; ep < EPOCHS; ep++) {
  for (let i = idx.length - 1; i > 0; i--) {
    const j = Math.floor(rand() * (i + 1));
    [idx[i], idx[j]] = [idx[j], idx[i]];
  }
  for (const i of idx) {
    const z = new Array(K).fill(0);
    for (const f of X[i]) {
      const w = get(f);
      for (let k = 0; k < K; k++) z[k] += w[k];
    }
    const m = Math.max(...z);
    const e = z.map((v) => Math.exp(v - m));
    const s = e.reduce((a, b) => a + b, 0);
    for (const f of X[i]) {
      const w = get(f);
      for (let k = 0; k < K; k++) w[k] -= lr * ((e[k] / s - (Y[i] === k ? 1 : 0)) + L2 * w[k]);
    }
  }
  lr *= 0.99;
}
const extractor = {};
for (const [f, w] of Object.entries(W)) if (w.some((v) => Math.abs(v) > 0.02)) extractor[f] = w.map((v) => Math.round(v * 100) / 100);

// ---------- Verifier: logistic regression over character n-grams ONLY (independent features) ----------
function trainLR(feat, epochs, l2, lr0) {
  const Wv = {};
  const g = (f) => (Wv[f] ||= new Array(K).fill(0));
  const Xv = TRAIN.map(([s]) => [...new Set(feat(s))]);
  let lrv = lr0;
  let sd = 11;
  const rnd = () => ((sd = (sd * 1103515245 + 12345) % 2147483648) / 2147483648);
  const order = TRAIN.map((_, i) => i);
  for (let ep = 0; ep < epochs; ep++) {
    for (let i = order.length - 1; i > 0; i--) {
      const j = Math.floor(rnd() * (i + 1));
      [order[i], order[j]] = [order[j], order[i]];
    }
    for (const i of order) {
      const z = new Array(K).fill(0);
      for (const f of Xv[i]) {
        const w = g(f);
        for (let k = 0; k < K; k++) z[k] += w[k];
      }
      const m = Math.max(...z);
      const e = z.map((v) => Math.exp(v - m));
      const s = e.reduce((a, b) => a + b, 0);
      for (const f of Xv[i]) {
        const w = g(f);
        for (let k = 0; k < K; k++) w[k] -= lrv * ((e[k] / s - (Y[i] === k ? 1 : 0)) + l2 * w[k]);
      }
    }
    lrv *= 0.99;
  }
  return Wv;
}
const Wv = trainLR(charGrams, 60, 0.0005, 0.05);
const verifier = {};
for (const [f, w] of Object.entries(Wv)) if (w.some((v) => Math.abs(v) > 0.04)) verifier[f] = w.map((v) => Math.round(v * 100) / 100);

const out = `// GENERATED by scripts/train.mjs from data/ml-train.js — do not edit by hand.
// ${TRAIN.length} training sentences · ${Object.keys(extractor).length} extractor features · ${Object.keys(verifier).length} verifier n-grams
export const MODEL = ${JSON.stringify({ trainedOn: TRAIN.length, labels: ML_LABELS, extractor, verifier })};
`;
fs.writeFileSync(new URL("../js/engine/ml-model.js", import.meta.url), out);
console.log(`trained on ${TRAIN.length} sentences; ${Object.keys(extractor).length} features; ${Object.keys(verifier).length} n-grams; ${(out.length / 1024).toFixed(0)} KB`);
